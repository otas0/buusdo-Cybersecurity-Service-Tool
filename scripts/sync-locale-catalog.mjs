#!/usr/bin/env node
/**
 * Emit shared/locale-catalog.json + desktop-app/public/js/locale-catalog.js
 * from i18n/locales.ts (parsed lightly via the built catalog constants).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);

// Load via tsx-compiled path: read locales.ts as text and eval the catalog array.
const src = fs.readFileSync(path.join(root, "i18n/locales.ts"), "utf8");
const match = src.match(/export const LOCALE_CATALOG[\s\S]*?=\s*(\[[\s\S]*?\])\s*as const/);
if (!match) {
  console.error("Could not parse LOCALE_CATALOG");
  process.exit(1);
}
const catalog = Function(`"use strict"; return (${match[1]});`)();

const regionOrderMatch = src.match(/export const LOCALE_REGION_ORDER[\s\S]*?=\s*(\[[\s\S]*?\]);/);
const regionOrder = regionOrderMatch
  ? Function(`"use strict"; return (${regionOrderMatch[1]});`)()
  : ["global", "east-asia", "europe", "southern-africa", "pacific", "southeast-asia"];

const labelsMatch = src.match(/export const LOCALE_REGION_LABELS[\s\S]*?=\s*(\{[\s\S]*?\});/);
const regionLabels = labelsMatch
  ? Function(`"use strict"; return (${labelsMatch[1]});`)()
  : {};

/** Desktop UI bags with native chrome (hasDesktopBag) — not EN-fallback. */
const desktopFirstClassBags = [
  "en",
  "pt-PT",
  "zh-Hans",
  "zh-Hant",
  "ja",
  "sv",
  "da",
  "fi",
  "nb",
  "de",
  "fr",
  "es",
  "it",
  "nl"
];

const payload = { regionOrder, regionLabels, catalog, desktopFirstClassBags };

fs.writeFileSync(path.join(root, "shared/locale-catalog.json"), JSON.stringify(payload, null, 2) + "\n");

const js = `/** Auto-generated by scripts/sync-locale-catalog.mjs — do not edit.
 * First-class desktop bags (native UI, not EN fallback): ${desktopFirstClassBags.join(", ")}.
 * Europe popup majors de/fr/es/it/nl are first-class alongside Nordic + CJK.
 */
export const LOCALE_CATALOG_DATA = ${JSON.stringify(payload, null, 2)};
`;
fs.writeFileSync(path.join(root, "desktop-app/public/js/locale-catalog.js"), js);
fs.writeFileSync(path.join(root, "extension/shared/locale-catalog.json"), JSON.stringify(payload, null, 2) + "\n");
console.log(`Synced locale catalog (${catalog.length} locales; first-class desktop ${desktopFirstClassBags.length})`);

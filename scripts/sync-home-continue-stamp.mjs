/**
 * Tiny build: emit ops/home-continue-stamp.browser.js from shared/home-continue-stamp.ts.
 *
 * Edit the stamp formula in ONE place (shared/home-continue-stamp.ts), then:
 *   npm run sync:home-continue-stamp
 *
 * Check (no write) — used by typecheck:
 *   npm run sync:home-continue-stamp:check
 *   node --import tsx scripts/sync-home-continue-stamp.mjs --check
 *
 * If you skip this script: edit three places —
 *   1. shared/home-continue-stamp.ts
 *   2. ops/home-continue-stamp.browser.js (or re-run this sync)
 *   3. tests/fixtures/home-continue-stamp-tag-only.html
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(".");
const sharedPath = path.join(root, "shared/home-continue-stamp.ts");
const outPath = path.join(root, "ops/home-continue-stamp.browser.js");
const checkOnly = process.argv.includes("--check");

const shared = readFileSync(sharedPath, "utf8");
const fn = shared.match(
  /export function stampLabelFromParams\(search:\s*string\):\s*string\s*\{([\s\S]*?)\n\}/
);
if (!fn) {
  console.error(
    "sync-home-continue-stamp: could not parse stampLabelFromParams from shared/home-continue-stamp.ts"
  );
  process.exit(1);
}

const expected = `/** Generated by scripts/sync-home-continue-stamp.mjs — do not edit.
 * Source: shared/home-continue-stamp.ts — re-run: npm run sync:home-continue-stamp
 */
function stampLabelFromParams(search) {${fn[1]}
}
`;

if (checkOnly) {
  if (!existsSync(outPath)) {
    console.error(
      "sync-home-continue-stamp --check: ops/home-continue-stamp.browser.js missing — run npm run sync:home-continue-stamp"
    );
    process.exit(1);
  }
  const actual = readFileSync(outPath, "utf8");
  if (actual !== expected) {
    console.error(
      "sync-home-continue-stamp --check: ops/home-continue-stamp.browser.js drifted from shared/home-continue-stamp.ts — run npm run sync:home-continue-stamp"
    );
    process.exit(1);
  }
  const mod = await import(pathToFileURL(sharedPath).href);
  const generated = new Function(`${actual}; return stampLabelFromParams;`)();
  if (generated("?tag=only") !== mod.stampLabelFromParams("?tag=only")) {
    console.error("sync-home-continue-stamp --check: runtime mismatch");
    process.exit(1);
  }
  console.log("sync-home-continue-stamp --check ok");
  process.exit(0);
}

writeFileSync(outPath, expected);
console.log(`wrote ${path.relative(root, outPath)}`);

const mod = await import(pathToFileURL(sharedPath).href);
const generated = new Function(`${readFileSync(outPath, "utf8")}; return stampLabelFromParams;`)();
const a = generated("?tag=only");
const b = mod.stampLabelFromParams("?tag=only");
if (a !== b) {
  console.error(`sync-home-continue-stamp: mismatch generated=${a} shared=${b}`);
  process.exit(1);
}
console.log(`sync-home-continue-stamp: ?tag=only ok → ${a}`);
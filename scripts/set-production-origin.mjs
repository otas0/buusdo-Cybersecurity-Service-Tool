#!/usr/bin/env node
/**
 * Record the live Cloudflare origin after first successful deploy.
 *
 *   npm run production:origin -- https://buusdocst.mtsu.workers.dev
 *   npm run production:origin -- https://buusdocst.mtsu.workers.dev --check-github-vars
 *   npm run production:origin -- --check-github-vars
 *
 * Updates: shared/production-origin.mjs, shared/production-site.json, README.md production block.
 * Optional --check-github-vars: gh variable list vs NEXT_PUBLIC_SITE_URL + PRODUCTION_HEALTH_URL.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const argv = process.argv.slice(2);
const checkGithubVars = argv.includes("--check-github-vars");
const urlArg =
  argv.find((a) => a !== "--check-github-vars") ||
  process.env.PRODUCTION_ORIGIN ||
  "";
const origin = String(urlArg)
  .trim()
  .replace(/\/$/, "");

async function checkGithubActionVars(expectedOrigin) {
  const { execFile } = await import("node:child_process");
  const { promisify } = await import("node:util");
  const execFileAsync = promisify(execFile);
  const want = String(expectedOrigin || "").replace(/\/$/, "");
  if (!want) {
    console.error("[production:origin] --check-github-vars needs an origin URL");
    process.exit(1);
  }
  try {
    const { stdout } = await execFileAsync(
      "gh",
      ["variable", "list", "--json", "name,value"],
      { cwd: root, timeout: 20_000 },
    );
    const rows = JSON.parse(stdout || "[]");
    const map = Object.fromEntries(
      (Array.isArray(rows) ? rows : []).map((r) => [r.name, String(r.value || "").replace(/\/$/, "")]),
    );
    let failed = false;
    for (const key of ["NEXT_PUBLIC_SITE_URL", "PRODUCTION_HEALTH_URL"]) {
      const got = map[key] || "";
      if (!got) {
        console.error(`[production:origin] GitHub var ${key} is unset — set to ${want}`);
        failed = true;
      } else if (got !== want) {
        console.error(
          `[production:origin] GitHub var ${key}=${got} ≠ expected ${want}`,
        );
        failed = true;
      } else {
        console.info(`[production:origin] GitHub var ${key} OK (${got})`);
      }
    }
    if (failed) process.exit(1);
  } catch (err) {
    console.error(
      "[production:origin] gh variable list failed:",
      err instanceof Error ? err.message : err,
    );
    process.exit(1);
  }
}

if (checkGithubVars && !origin) {
  // Allow: npm run production:origin -- --check-github-vars  (uses production-site.json)
  try {
    const site = JSON.parse(
      readFileSync(join(root, "shared/production-site.json"), "utf8"),
    );
    const fromSite = String(site.productionOrigin || "").replace(/\/$/, "");
    if (!fromSite) throw new Error("productionOrigin empty");
    await checkGithubActionVars(fromSite);
    process.exit(0);
  } catch (err) {
    console.error(
      "[production:origin] --check-github-vars without URL needs shared/production-site.json",
      err instanceof Error ? err.message : err,
    );
    process.exit(1);
  }
}

if (!/^https:\/\/[^\s/]+/i.test(origin)) {
  console.error(
    "Usage: npm run production:origin -- https://buusdocst.mtsu.workers.dev [--check-github-vars]"
  );
  process.exit(1);
}

let host;
try {
  host = new URL(origin).host;
} catch {
  console.error("Invalid URL:", origin);
  process.exit(1);
}

const canonicalHost = host.replace(/^www\./i, "");
if (host.startsWith("www.")) {
  console.warn(
    `[production:origin] Prefer apex without www for NEXT_PUBLIC_SITE_URL (got ${host}). Storing as-is; set DNS www→apex redirect.`
  );
}

function patchProductionOriginExport(relPath) {
  const full = join(root, relPath);
  let src = readFileSync(full, "utf8");
  if (!/export const PRODUCTION_ORIGIN =/.test(src)) {
    console.error(`${relPath} missing PRODUCTION_ORIGIN export`);
    process.exit(1);
  }
  src = src.replace(
    /export const PRODUCTION_ORIGIN = "[^"]*";/,
    `export const PRODUCTION_ORIGIN = ${JSON.stringify(origin)};`
  );
  writeFileSync(full, src, "utf8");
}

patchProductionOriginExport("shared/production-origin.mjs");
patchProductionOriginExport("extension/shared/api-base-migrate.mjs");

const jsonPath = join(root, "shared", "production-site.json");
const site = {
  productionOrigin: origin,
  canonicalHost,
  updatedAt: new Date().toISOString(),
  notes:
    "Generated by npm run production:origin. Extension DEFAULT_API_BASE and desktop WEBSITE_CHECK_URL default follow this origin."
};
writeFileSync(jsonPath, `${JSON.stringify(site, null, 2)}\n`, "utf8");

// Ensure MV3 host_permissions include the production origin for Website API fetch.
const manifestPath = join(root, "extension", "manifest.json");
try {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const pattern = `${origin}/*`;
  const hosts = Array.isArray(manifest.host_permissions) ? manifest.host_permissions : [];
  const kept = hosts.filter((h) => !/workers\.dev\/\*$/i.test(String(h)));
  if (!kept.includes(pattern)) kept.push(pattern);
  manifest.host_permissions = kept;
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  console.info(`[production:origin] extension host_permissions workers.dev → ${pattern}`);
} catch (err) {
  console.warn(
    "[production:origin] could not patch extension/manifest.json:",
    err instanceof Error ? err.message : err
  );
}

const promoPath = join(root, "docs", "PUBLIC_PROMOTION.md");
try {
  let promo = readFileSync(promoPath, "utf8");
  promo = promo.replace(
    /https:\/\/[a-z0-9.-]+\.workers\.dev/gi,
    origin
  );
  writeFileSync(promoPath, promo, "utf8");
  console.info(`[production:origin] updated docs/PUBLIC_PROMOTION.md → ${origin}`);
} catch (err) {
  console.warn(
    "[production:origin] could not patch PUBLIC_PROMOTION.md:",
    err instanceof Error ? err.message : err
  );
}

const readmePath = join(root, "README.md");

let readme = readFileSync(readmePath, "utf8");
const block = `### Live production origin

- **Origin:** \`${origin}\`
- **Canonical host:** \`${canonicalHost}\` (prefer apex; redirect \`www\` → apex)
- Set after deploy: \`npm run production:origin -- ${origin}\`
- Health: \`npm run health:prod -- --url ${origin}\`
- Check smoke: \`npm run check:prod -- --url ${origin}\`

Ops docs: [PRODUCTION_HOSTING](docs/PRODUCTION_HOSTING.md) · [LAUNCH_CHECKLIST](docs/LAUNCH_CHECKLIST.md) · [DEPLOY_SECRETS](docs/DEPLOY_SECRETS.md) · [CUSTOM_DOMAIN_REDEPLOY](docs/CUSTOM_DOMAIN_REDEPLOY.md) · [CANONICAL_HOST](docs/CANONICAL_HOST.md) · [CLOUDFLARE_ALERTS](docs/CLOUDFLARE_ALERTS.md) · [LOCAL_CF_CONNECTIVITY](docs/LOCAL_CF_CONNECTIVITY.md) · [POST_LAUNCH_48H](docs/POST_LAUNCH_48H.md) · [VINEXT_UPGRADE_1_4](docs/VINEXT_UPGRADE_1_4.md)

Scheduled monitor: set GitHub Actions variable \`PRODUCTION_HEALTH_URL\` → workflow **Production health**.  
Optional deploy: Actions → **Deploy Cloudflare** with secrets from [DEPLOY_SECRETS.md](docs/DEPLOY_SECRETS.md).
`;

if (/### Live production origin[\s\S]*?(?=\n### |\n## |$)/.test(readme)) {
  readme = readme.replace(
    /### Live production origin[\s\S]*?(?=\n### |\n## |$)/,
    `${block}\n`
  );
} else if (/### Production hosting \(Cloudflare\)/.test(readme)) {
  readme = readme.replace(
    /### Production hosting \(Cloudflare\)/,
    `### Production hosting (Cloudflare)\n\n${block}`
  );
} else {
  readme += `\n${block}\n`;
}
writeFileSync(readmePath, readme, "utf8");

console.info(`[production:origin] PRODUCTION_ORIGIN=${origin}`);
console.info(
  `[production:origin] updated shared/production-origin.mjs + extension/shared/api-base-migrate.mjs + production-site.json + README.md`
);
console.info(`[production:origin] next: export NEXT_PUBLIC_SITE_URL=${origin} && npm run deploy:cloudflare`);
console.info("");
console.info("[production:origin] GitHub Actions — set BOTH repo variables (Settings → Variables):");
console.info(`  NEXT_PUBLIC_SITE_URL=${origin}`);
console.info(`  PRODUCTION_HEALTH_URL=${origin}`);
console.info("Then Actions → Deploy Cloudflare (production) so OG/metadataBase bake the canonical host.");
console.info(
  `After deploy: Facebook Sharing Debugger / Twitter Card Validator on ${origin}/og.png`,
);
console.info(
  `Verify vars: npm run production:origin -- ${origin} --check-github-vars`,
);

if (checkGithubVars) {
  await checkGithubActionVars(origin);
}

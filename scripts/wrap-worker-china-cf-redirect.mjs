/**
 * Post-vinext-build: wrap dist/server Worker entry so CN uses request.cf.country.
 *
 * CF-IPCountry is often missing as a header on workers.dev unless Managed Transforms
 * add visitor location headers. request.cf.country is always set on Workers.
 *
 *   node scripts/wrap-worker-china-cf-redirect.mjs
 *
 * Writes dist/server/china-cf-entry.js and sets wrangler.json main → that file.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const serverDir = path.join(root, "dist/server");
const entryPath = path.join(serverDir, "china-cf-entry.js");
const wranglerPath = path.join(serverDir, "wrangler.json");
const chinaPagesPath = path.join(root, "shared/china-pages.json");

if (!existsSync(path.join(serverDir, "index.js"))) {
  console.error("[wrap-china-cf] missing dist/server/index.js — run vinext build first");
  process.exit(1);
}

const chinaPages = JSON.parse(readFileSync(chinaPagesPath, "utf8"));
const pagesOrigin = String(chinaPages.url || "https://otas0.github.io/buusdocst/").replace(
  /\/$/,
  ""
);

const entry = `/**
 * Auto-generated by scripts/wrap-worker-china-cf-redirect.mjs — do not edit.
 * Forces CN (request.cf.country) HTML → China Pages; injects cf-ipcountry for App Router.
 */
import app from "./index.js";

const PAGES_ORIGIN = ${JSON.stringify(pagesOrigin)};
const STAY_COOKIE = "buusdocst-china-workers-stay";
const STAY_PARAM = "china_workers_stay";

function pagesDest(pathname) {
  const p = String(pathname || "/").split("?")[0] || "/";
  if (p === "/en" || p.startsWith("/en/")) return PAGES_ORIGIN + "/en.html";
  return PAGES_ORIGIN + "/";
}

function skipPath(pathname) {
  const p = String(pathname || "/");
  if (p.startsWith("/api/")) return true;
  if (p.startsWith("/_next/")) return true;
  if (p.startsWith("/brand/") || p.startsWith("/promo/") || p.startsWith("/assets/")) return true;
  if (/\\.[a-zA-Z0-9]{1,8}$/.test(p)) return true;
  return false;
}

function cookieHasStay(cookieHeader) {
  if (!cookieHeader) return false;
  return /(?:^|;\\s*)buusdocst-china-workers-stay=1(?:;|$)/.test(cookieHeader);
}

function countryFrom(request) {
  const cf = request && request.cf;
  const fromCf = cf && typeof cf.country === "string" ? cf.country : "";
  const fromHeader =
    request.headers.get("cf-ipcountry") ||
    request.headers.get("CF-IPCountry") ||
    request.headers.get("x-vercel-ip-country") ||
    "";
  return String(fromCf || fromHeader || "")
    .trim()
    .toUpperCase();
}

function withCountryHeader(request, country) {
  if (!country || request.headers.get("cf-ipcountry")) return request;
  const headers = new Headers(request.headers);
  headers.set("cf-ipcountry", country);
  // Cloning from the inbound Request preserves request.cf on Cloudflare Workers.
  return new Request(request, { headers });
}

function setStayCookie(response, value) {
  const res = new Response(response.body, response);
  if (value === "1") {
    res.headers.append(
      "Set-Cookie",
      STAY_COOKIE + "=1; Path=/; Max-Age=28800; SameSite=Lax"
    );
  } else {
    res.headers.append(
      "Set-Cookie",
      STAY_COOKIE + "=; Path=/; Max-Age=0; SameSite=Lax"
    );
  }
  return res;
}

const inner = app && typeof app.fetch === "function" ? app : { fetch: app };

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    const stayParam = url.searchParams.get(STAY_PARAM);
    const country = countryFrom(request);
    const req = withCountryHeader(request, country);

    if (stayParam === "1") {
      const res = await inner.fetch(req, env, ctx);
      return setStayCookie(res instanceof Response ? res : new Response(res), "1");
    }
    if (stayParam === "0") {
      const res = await inner.fetch(req, env, ctx);
      return setStayCookie(res instanceof Response ? res : new Response(res), "0");
    }

    if (
      country === "CN" &&
      !skipPath(url.pathname) &&
      !cookieHasStay(request.headers.get("cookie"))
    ) {
      return Response.redirect(pagesDest(url.pathname), 302);
    }

    return inner.fetch(req, env, ctx);
  }
};
`;

writeFileSync(entryPath, entry);
console.log("[wrap-china-cf] wrote", path.relative(root, entryPath));

if (existsSync(wranglerPath)) {
  const w = JSON.parse(readFileSync(wranglerPath, "utf8"));
  w.main = "china-cf-entry.js";
  writeFileSync(wranglerPath, `${JSON.stringify(w)}\n`);
  console.log("[wrap-china-cf] wrangler.json main → china-cf-entry.js");
} else {
  console.warn("[wrap-china-cf] dist/server/wrangler.json missing — deploy may still use index.js");
}

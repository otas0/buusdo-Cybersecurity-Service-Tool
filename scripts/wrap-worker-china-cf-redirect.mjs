/**
 * Post-vinext-build: wrap dist/server Worker entry so CN uses request.cf.country.
 *
 * CF-IPCountry is often missing as a header on workers.dev unless Managed Transforms
 * add visitor location headers. request.cf.country is always set on Workers.
 *
 * Also sets assets.run_worker_first to the vinext-recommended pattern list so:
 *   - HTML / public paths run the Worker first (CN wrap cannot be skipped by Assets)
 *   - /_next/static/* is served by Assets directly (boolean `true` 404s CSS/JS — vinext docs)
 *
 *   node scripts/wrap-worker-china-cf-redirect.mjs
 *   node scripts/wrap-worker-china-cf-redirect.mjs --check
 *
 * Writes dist/server/china-cf-entry.js and sets wrangler.json main → that file.
 *
 * IMPORTANT: If the client cannot TCP-connect to *.workers.dev (common on some
 * mainland networks), this wrap never runs — open https://otas0.github.io/buusdocst/
 * directly. See docs/LOCAL_CF_CONNECTIVITY.md + docs/CHINA_GITHUB_PAGES.md.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { RUN_WORKER_FIRST, isValidRunWorkerFirst } from "./run-worker-first.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const serverDir = path.join(root, "dist/server");
const entryPath = path.join(serverDir, "china-cf-entry.js");
const wranglerPath = path.join(serverDir, "wrangler.json");
const chinaPagesPath = path.join(root, "shared/china-pages.json");
const checkOnly = process.argv.includes("--check");

const chinaPages = JSON.parse(readFileSync(chinaPagesPath, "utf8"));
const pagesOrigin = String(chinaPages.url || "https://otas0.github.io/buusdocst/").replace(
  /\/$/,
  ""
);

/** Countries that force HTML → China Pages. Product decision: CN only (not HK/MO). */
const FORCE_COUNTRIES_JSON = JSON.stringify(["CN"]);

function expectedEntrySource() {
  return `/**
 * Auto-generated by scripts/wrap-worker-china-cf-redirect.mjs — do not edit.
 * Forces CN (request.cf.country) HTML → China Pages; injects cf-ipcountry for App Router.
 * Product: CN only (HK/MO not force-redirected — docs/CHINA_GITHUB_PAGES.md).
 */
import app from "./index.js";

const PAGES_ORIGIN = ${JSON.stringify(pagesOrigin)};
const STAY_COOKIE = "buusdocst-china-workers-stay";
const STAY_PARAM = "china_workers_stay";
const FORCE_COUNTRIES = new Set(${FORCE_COUNTRIES_JSON});
const WRAP_HEADER = "x-buusdocst-china-wrap";
const COUNTRY_HEADER = "x-buusdocst-cf-country";

function pagesDest(pathname) {
  const p = String(pathname || "/").split("?")[0] || "/";
  if (p === "/en" || p.startsWith("/en/")) return PAGES_ORIGIN + "/en.html";
  return PAGES_ORIGIN + "/";
}

function skipPath(pathname) {
  const p = String(pathname || "/");
  if (p.startsWith("/api/")) return true;
  if (p.startsWith("/_next/")) return true;
  if (p.startsWith("/brand/") || p.startsWith("/promo/") || p.startsWith("/assets/")) return true;
  if (/\\.[a-zA-Z0-9]{1,8}$/.test(p)) return true;
  return false;
}

function cookieHasStay(cookieHeader) {
  if (!cookieHeader) return false;
  return /(?:^|;\\s*)buusdocst-china-workers-stay=1(?:;|$)/.test(cookieHeader);
}

function countryFrom(request) {
  const cf = request && request.cf;
  const fromCf = cf && typeof cf.country === "string" ? cf.country : "";
  const fromHeader =
    request.headers.get("cf-ipcountry") ||
    request.headers.get("CF-IPCountry") ||
    request.headers.get("x-vercel-ip-country") ||
    "";
  return String(fromCf || fromHeader || "")
    .trim()
    .toUpperCase();
}

function withCountryHeader(request, country) {
  if (!country || request.headers.get("cf-ipcountry")) return request;
  const headers = new Headers(request.headers);
  headers.set("cf-ipcountry", country);
  return new Request(request, { headers });
}

function markWrap(response, country) {
  try {
    const res = new Response(response.body, response);
    res.headers.set(WRAP_HEADER, "1");
    if (country) res.headers.set(COUNTRY_HEADER, country);
    return res;
  } catch {
    return response;
  }
}

function setStayCookie(response, value, country) {
  const res = markWrap(response instanceof Response ? response : new Response(String(response)), country);
  if (value === "1") {
    res.headers.append(
      "Set-Cookie",
      STAY_COOKIE + "=1; Path=/; Max-Age=28800; SameSite=Lax"
    );
  } else {
    res.headers.append(
      "Set-Cookie",
      STAY_COOKIE + "=; Path=/; Max-Age=0; SameSite=Lax"
    );
  }
  return res;
}

const inner = app && typeof app.fetch === "function" ? app : { fetch: app };

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    const stayParam = url.searchParams.get(STAY_PARAM);
    const country = countryFrom(request);
    const req = withCountryHeader(request, country);

    if (stayParam === "1") {
      const res = await inner.fetch(req, env, ctx);
      return setStayCookie(res instanceof Response ? res : new Response(res), "1", country);
    }
    if (stayParam === "0") {
      const res = await inner.fetch(req, env, ctx);
      return setStayCookie(res instanceof Response ? res : new Response(res), "0", country);
    }

    if (
      FORCE_COUNTRIES.has(country) &&
      !skipPath(url.pathname) &&
      !cookieHasStay(request.headers.get("cookie"))
    ) {
      const redirect = Response.redirect(pagesDest(url.pathname), 302);
      redirect.headers.set(WRAP_HEADER, "1");
      redirect.headers.set(COUNTRY_HEADER, country);
      redirect.headers.set("Cache-Control", "private, no-store");
      return redirect;
    }

    const out = await inner.fetch(req, env, ctx);
    return markWrap(out instanceof Response ? out : new Response(out), country);
  }
};
`;
}

function ensureRunWorkerFirst(w) {
  const prev = w.assets;
  const base =
    prev && typeof prev === "object" && !Array.isArray(prev)
      ? { ...prev }
      : typeof prev === "string"
        ? { directory: prev }
        : { directory: "../client" };
  // Binding silences wrangler "run_worker_first without an assets binding" and
  // keeps vinext ASSETS.fetch working when the Worker runs first.
  if (!base.binding) base.binding = "ASSETS";
  base.run_worker_first = [...RUN_WORKER_FIRST];
  w.assets = base;
}

if (checkOnly) {
  if (!existsSync(entryPath)) {
    console.error("[wrap-china-cf] --check FAIL: missing dist/server/china-cf-entry.js — run without --check after vinext build");
    process.exit(1);
  }
  if (!existsSync(wranglerPath)) {
    console.error("[wrap-china-cf] --check FAIL: missing dist/server/wrangler.json");
    process.exit(1);
  }
  const w = JSON.parse(readFileSync(wranglerPath, "utf8"));
  if (w.main !== "china-cf-entry.js") {
    console.error(
      `[wrap-china-cf] --check FAIL: wrangler.json main="${w.main}" (want china-cf-entry.js)`
    );
    process.exit(1);
  }
  const assets = w.assets && typeof w.assets === "object" ? w.assets : {};
  if (!isValidRunWorkerFirst(assets.run_worker_first)) {
    console.error(
      `[wrap-china-cf] --check FAIL: assets.run_worker_first=${JSON.stringify(assets.run_worker_first)} (want ${JSON.stringify(RUN_WORKER_FIRST)} — boolean true 404s /_next/static)`
    );
    process.exit(1);
  }
  if (assets.binding !== "ASSETS") {
    console.error(
      `[wrap-china-cf] --check FAIL: assets.binding=${JSON.stringify(assets.binding)} (want "ASSETS")`
    );
    process.exit(1);
  }
  const cur = readFileSync(entryPath, "utf8");
  if (!cur.includes("request.cf") || !cur.includes("FORCE_COUNTRIES") || !cur.includes(pagesOrigin)) {
    console.error("[wrap-china-cf] --check FAIL: china-cf-entry.js missing expected markers");
    process.exit(1);
  }
  if (!cur.includes("x-buusdocst-cf-country")) {
    console.error("[wrap-china-cf] --check FAIL: china-cf-entry.js missing country debug header");
    process.exit(1);
  }
  console.log(
    "[wrap-china-cf] --check OK (main=china-cf-entry.js, run_worker_first excludes /_next/static)"
  );
  process.exit(0);
}

if (!existsSync(path.join(serverDir, "index.js"))) {
  console.error("[wrap-china-cf] missing dist/server/index.js — run vinext build first");
  process.exit(1);
}

writeFileSync(entryPath, expectedEntrySource());
console.log("[wrap-china-cf] wrote", path.relative(root, entryPath));

if (existsSync(wranglerPath)) {
  const w = JSON.parse(readFileSync(wranglerPath, "utf8"));
  w.main = "china-cf-entry.js";
  ensureRunWorkerFirst(w);
  writeFileSync(wranglerPath, `${JSON.stringify(w)}\n`);
  console.log(
    "[wrap-china-cf] wrangler.json main → china-cf-entry.js; assets.run_worker_first=",
    JSON.stringify(RUN_WORKER_FIRST)
  );
} else {
  console.warn("[wrap-china-cf] dist/server/wrangler.json missing — deploy may still use index.js");
}

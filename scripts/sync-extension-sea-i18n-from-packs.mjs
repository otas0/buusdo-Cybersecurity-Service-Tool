#!/usr/bin/env node
/**
 * Overlay website pack chrome onto extension STRINGS for mi / th / vi.
 * Preserves extension-only keys (lists*, account*, websiteApi*) from the prior bag.
 *
 *   node scripts/sync-extension-sea-i18n-from-packs.mjs
 *   node scripts/sync-extension-sea-i18n-from-packs.mjs --check
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const i18nPath = path.join(root, "extension/shared/i18n.js");
const packsDir = path.join(root, "i18n/packs");
const LOCALES = ["mi", "th", "vi"];

/** extension key → website pack key */
const MAP = {
  appTitle: "prototype",
  scan: "go",
  scanning: "checking",
  statusStandby: "lightStandby",
  statusSafe: "lightSafe",
  statusCaution: "lightCaution",
  statusDanger: "lightDanger",
  statusIdle: "lightIdle",
  privacyLabel: "privacyLabel",
  privacyOff: "privacyOff",
  privacyLocal: "privacyLocal",
  privacyShare: "privacyShare",
  privacyHint: "privacyNote",
  langLabel: "navCheck",
  toastPhishing: "lightDanger",
  toastTracker: "lightCaution",
  toastTrackers: "lightCaution"
};

const markerStart = "/* __EXTENSION_SEA_PACK_OVERLAY_START__ */";
const markerEnd = "/* __EXTENSION_SEA_PACK_OVERLAY_END__ */";

function loadPack(id) {
  const p = path.join(packsDir, `${id}.json`);
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

function extractBag(src, id) {
  // Last bag in STRINGS may omit the trailing comma before `};`.
  const re = new RegExp(`\\n  ${id}: (\\{[\\s\\S]*?\\n  \\}),?`);
  const m = src.match(re);
  if (!m) return null;
  try {
    return Function(`"use strict"; return (${m[1]});`)();
  } catch {
    return null;
  }
}

function extractEn(src) {
  return extractBag(src, "en");
}

function applyOverlay(base, pack) {
  const out = { ...base };
  if (!pack) return out;
  for (const [ext, web] of Object.entries(MAP)) {
    if (pack[web]?.trim()) out[ext] = pack[web];
  }
  return out;
}

function bagLiteral(id, bag) {
  const body = JSON.stringify(bag, null, 2)
    .split("\n")
    .map((line, i) => (i === 0 ? line : `  ${line}`))
    .join("\n");
  // STRINGS uses unquoted keys for mi/th/vi: mi: { ... },
  return `  ${id}: ${body.replace(/^\{\n/, "{\n").replace(/\n\}$/, "\n  }")},`;
}

function buildBlock(bags) {
  return [
    markerStart,
    "// Auto-generated by scripts/sync-extension-sea-i18n-from-packs.mjs — pack chrome overlay; other keys preserved.",
    ...LOCALES.map((id) => bagLiteral(id, bags[id])),
    markerEnd
  ].join("\n");
}

const src = fs.readFileSync(i18nPath, "utf8");
const enBag = extractEn(src);
if (!enBag) {
  console.error("[sync-extension-sea-i18n] could not parse STRINGS.en");
  process.exit(1);
}

const bags = {};
for (const id of LOCALES) {
  const pack = loadPack(id);
  if (!pack) {
    console.error(`[sync-extension-sea-i18n] missing pack ${id}.json`);
    process.exit(1);
  }
  const prior = extractBag(src, id) || { ...enBag };
  bags[id] = applyOverlay(prior, pack);
  for (const key of Object.keys(enBag)) {
    if (!bags[id][key]?.toString().trim()) {
      console.error(`[sync-extension-sea-i18n] ${id} missing key after overlay: ${key}`);
      process.exit(1);
    }
  }
}

const block = buildBlock(bags);
let next = src;
if (src.includes(markerStart) && src.includes(markerEnd)) {
  next = src.replace(
    new RegExp(
      `${markerStart.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${markerEnd.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`
    ),
    () => block
  );
} else {
  // Replace hand mi/th/vi bags with marker block (after zh-Hans bag closing).
  const miStart = src.search(/\n  mi: \{/);
  if (miStart < 0) {
    console.error("[sync-extension-sea-i18n] could not find mi bag to replace");
    process.exit(1);
  }
  const afterVi = src.indexOf("\n};", src.search(/\n  vi: \{/));
  if (afterVi < 0) {
    console.error("[sync-extension-sea-i18n] could not find end of vi bag");
    process.exit(1);
  }
  // Find closing of vi object: line with `  },` then `};` of STRINGS — vi ends with `  }` before `};`
  const viMatch = src.match(/\n  vi: \{[\s\S]*?\n  \}\n\};/);
  if (!viMatch) {
    console.error("[sync-extension-sea-i18n] could not match mi..vi block");
    process.exit(1);
  }
  next = src.replace(/\n  mi: \{[\s\S]*?\n  \}\n\};/, `\n${block}\n};`);
}

if (checkOnly) {
  if (src !== next) {
    console.error("[sync-extension-sea-i18n] drift — run: npm run sync:extension-sea-i18n");
    process.exit(1);
  }
  console.info(`[sync-extension-sea-i18n] OK (${LOCALES.join(",")})`);
  process.exit(0);
}

fs.writeFileSync(i18nPath, next);
console.log(`[sync-extension-sea-i18n] wrote ${LOCALES.join(",")} overlays → extension/shared/i18n.js`);

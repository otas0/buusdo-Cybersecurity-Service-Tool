#!/usr/bin/env node
/**
 * Scan i18n/packs/*.json (skip _*.json snapshots) and rewrite i18n/pack-index.ts imports.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const packsDir = path.join(root, "i18n", "packs");
const outFile = path.join(root, "i18n", "pack-index.ts");

const files = fs
  .readdirSync(packsDir)
  .filter((f) => f.endsWith(".json") && !f.startsWith("_"))
  .sort();

const imports = files
  .map((f) => {
    const id = f.replace(/\.json$/, "");
    const varName = id.replace(/[^a-zA-Z0-9]/g, "_");
    return { id, varName, f };
  })
  .map(({ id, varName, f }) => `import pack_${varName} from "./packs/${f}";`);

const entries = files
  .map((f) => {
    const id = f.replace(/\.json$/, "");
    const varName = id.replace(/[^a-zA-Z0-9]/g, "_");
    return `  ${JSON.stringify(id)}: pack_${varName} as LocalePack,`;
  })
  .join("\n");

const body = `/**
 * Locale override packs (partial). Auto-generated by scripts/gen-pack-index.mjs — do not edit by hand.
 */
export type LocalePack = Record<string, string>;

${imports.join("\n")}

export const LOCALE_PACKS: Record<string, LocalePack> = {
${entries || "  // no packs yet"}
};
`;

fs.writeFileSync(outFile, body);
console.log(`Wrote ${outFile} (${files.length} packs)`);

/** @param {string|null|undefined} lang */
export function normalizeUiLang(lang) {
  const raw = String(lang || "").trim();
  if (raw === "pt-PT" || raw === "pt") return "pt-PT";
  if (raw === "zh-Hans" || raw === "zh" || raw === "zh-CN" || raw === "zh-SG") return "zh-Hans";
  return "en";
}


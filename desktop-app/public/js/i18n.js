export function t(lang, key, vars = {}) {
  const table = STRINGS[lang] || STRINGS.en;
  let out = table[key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}
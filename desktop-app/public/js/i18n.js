/**
 * UI strings — locale packs (en, pt-PT, zh-Hans).
 * Kept aligned with extension/shared/i18n.js (desktop-specific keys added).
 * Prefer zh-Hans — never persist bare `zh`.
 */

/** Shipped desktop string bags (others fall back to EN via t()). */
const DESKTOP_BAGS = new Set(["en", "pt-PT", "zh-Hans", "ja", "zh-Hant"]);

/** @param {string|null|undefined} lang */
export function normalizeUiLang(lang) {
  const raw = String(lang || "").trim();
  if (!raw) return "en";
  if (raw === "pt" || raw === "pt-pt") return "pt-PT";
  if (raw === "pt-BR" || raw === "pt-br") return "pt-BR";
  if (raw === "zh" || raw === "zh-CN" || raw === "zh-SG") return "zh-Hans";
  if (raw === "zh-TW" || raw === "zh-HK" || raw === "zh-MO") return "zh-Hant";
  if (raw === "jp") return "ja";
  if (raw === "tl") return "fil";
  if (raw === "no") return "nb";
  // Persist any catalog-like id; UI copy falls back to EN when bag missing.
  if (/^[a-z]{2,3}(-[A-Za-z0-9]+)?$/.test(raw) || raw === "zh-Hans" || raw === "zh-Hant" || raw === "pt-PT" || raw === "pt-BR") {
    return raw;
  }
  return "en";
}

export function hasDesktopBag(lang) {
  return DESKTOP_BAGS.has(normalizeUiLang(lang));
}

